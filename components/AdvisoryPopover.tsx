'use client';

import React, { useState, useRef, useEffect } from 'react';
import { Shield, Sparkles, X } from 'lucide-react';

interface AdvisoryPopoverProps {
  title?: string;
  explanation?: string;
  legalReference?: string;
  className?: string;
}

export default function AdvisoryPopover({
  title = 'AI & Automated Decision-Support Advisory',
  explanation = 'This risk projection, date extraction, or scheduling proposal is generated by SAMAY decision-support algorithms to assist AICTE officers in preventing student intake disruption. Under Section 10(k) of the AICTE Act 1987, all automated insights are non-binding and require competent human officer scrutiny.',
  legalReference = 'AICTE Approval Process Handbook (APH 2024-27 Clause 5.2) & AICTE Act 1987',
  className = ''
}: AdvisoryPopoverProps) {
  const [isOpen, setIsOpen] = useState(false);
  const popoverRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    function handleClickOutside(event: MouseEvent) {
      if (popoverRef.current && !popoverRef.current.contains(event.target as Node)) {
        setIsOpen(false);
      }
    }
    if (isOpen) {
      document.addEventListener('mousedown', handleClickOutside);
    }
    return () => {
      document.removeEventListener('mousedown', handleClickOutside);
    };
  }, [isOpen]);

  return (
    <div className={`relative inline-flex items-center ${className}`} ref={popoverRef}>
      <button
        type="button"
        onClick={(e) => {
          e.stopPropagation();
          setIsOpen(!isOpen);
        }}
        className="inline-flex items-center space-x-1 px-2 py-0.5 rounded-full text-[10px] font-semibold bg-amber-50 hover:bg-amber-100 text-amber-900 border border-amber-200/80 shadow-2xs transition-all duration-200 cursor-pointer"
        title="View regulatory explanation"
      >
        <Sparkles className="w-2.5 h-2.5 text-amber-600 shrink-0" strokeWidth={1.75} />
        <span>Advisory only</span>
        <span className="font-bold text-amber-800 underline decoration-amber-400">Why?</span>
      </button>

      {isOpen && (
        <div
          onClick={(e) => e.stopPropagation()}
          className="absolute z-50 left-0 top-full mt-1.5 w-72 sm:w-80 glass-dropdown rounded-2xl p-4 text-xs shadow-xl border border-amber-200/80 animate-fade-in text-[#0F241C]"
        >
          <div className="flex items-start justify-between pb-2 border-b border-emerald-950/[0.06] mb-2.5">
            <div className="flex items-center space-x-1.5">
              <Shield className="w-4 h-4 text-emerald-700 shrink-0" strokeWidth={1.75} />
              <span className="font-bold text-[11px] text-emerald-950 tracking-tight">{title}</span>
            </div>
            <button
              type="button"
              onClick={() => setIsOpen(false)}
              className="p-1 rounded-full text-emerald-950/40 hover:text-emerald-950 hover:bg-emerald-950/[0.04]"
            >
              <X className="w-3.5 h-3.5" strokeWidth={1.75} />
            </button>
          </div>

          <p className="text-[11px] text-emerald-950/70 leading-relaxed">
            {explanation}
          </p>

          <div className="mt-3 pt-2.5 border-t border-emerald-950/[0.06] bg-yellow-50/40 p-2 rounded-xl border border-yellow-200/60">
            <span className="text-[9px] font-bold text-amber-900 uppercase tracking-wider block">
              Regulatory Basis:
            </span>
            <span className="text-[10px] text-emerald-950/70 font-medium">
              {legalReference}
            </span>
          </div>
        </div>
      )}
    </div>
  );
}
